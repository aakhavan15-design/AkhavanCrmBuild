import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const colors = read('src/theme/colors.css');
const tailwind = read('tailwind.config.js');
const index = read('src/index.css');
const theme = read('src/theme/ThemeProvider.tsx');
const nav = read('src/lib/navigation.ts');
const drawer = read('src/components/NavigationDrawer.tsx');
const sidebar = read('src/components/DesktopSidebar.tsx');
const line = read('src/components/charts/LineChart.tsx');
const walk = dir => readdirSync(new URL(`../${dir}`, import.meta.url), { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]);
const uiFiles = [...walk('src/components'), ...walk('src/workspaces')].filter(file => /\.(tsx?|css)$/.test(file));
for (const file of uiFiles) {
  assert.doesNotMatch(read(file), /#[0-9A-Fa-f]{3,8}\b/, `${file} must consume semantic color tokens instead of hardcoded hex values`);
  assert.doesNotMatch(read(file), /\brgba?\([^)]*\)/, `${file} must consume semantic color tokens instead of hardcoded RGB values`);
}
const bar = read('src/components/charts/BarChart.tsx');
const modal = read('src/components/ui/Modal.tsx');
const allocation = read('src/components/charts/AllocationBar.tsx');
const quoteWizard = read('src/components/QuoteWizardModal.tsx');
const customerSchema = read('src/services/dynamicFormEngine.ts');
const financeWorkspace = read('src/components/FinanceWorkspace.tsx');
assert.match(modal, /shadow-\[var\(--shadow-modal\)\]/, 'modal elevation must consume the canonical semantic shadow token');
assert.doesNotMatch(modal, /rgba?\(/, 'modal must not define a local shadow color');
assert.doesNotMatch(allocation, /rgba?\(/, 'allocation chart must not define a local highlight color');
assert.match(quoteWizard, /!Number\.isSafeInteger\(qty\) \|\| qty <= 0 \|\| !Number\.isFinite\(price\) \|\| price <= 0/, 'quote line entry must reject invalid quantity/price instead of silently coercing defaults');
assert.match(quoteWizard, /مقدار نامعتبر با پیش‌فرض جایگزین نشد/);
assert.match(customerSchema, /id: 'customer_profile_schema'[\s\S]*name: 'name'[\s\S]*validation: \{ required: true, minLength: 3 \}/);
assert.match(customerSchema, /id: 'finance_receipt_schema'[\s\S]*name: 'amount'[\s\S]*validation: \{ required: true, min: 1000 \}/);
assert.match(financeWorkspace, /checkReceipt\(state,[\s\S]*requireEvidence,[\s\S]*hasEvidence/);
assert.match(colors, /--c-primary:\s*var\(--c-cobalt\)/);
assert.match(colors, /--c-chart-1:/);
assert.match(colors, /--font-family-ui:/);
assert.match(colors, /--c-ink-muted: #64748B/);
assert.match(colors, /\[data-theme="dark"\]/);
assert.doesNotMatch(tailwind, /#(?:71364B|9C5573|F8FAFC)/i, 'Tailwind semantic palette must not fork the design tokens');
assert.match(tailwind, /var\(--c-primary\)/);
assert.match(index, /--color-chart-1: var\(--c-chart-1\)/);
assert.match(index, /--color-amber-50: var\(--c-warning-soft\)/);
assert.match(index, /--color-emerald-50: var\(--c-success-soft\)/);
assert.match(index, /--color-slate-700: var\(--c-ink-main\)/);
assert.match(index, /font-family: var\(--font-family-ui\)/);
assert.match(index, /se-atmosphere-root .*display: none !important/);
assert.match(theme, /getPropertyValue\('--c-theme-color'\)/, 'browser theme color must use the active theme token');
assert.match(nav, /children\?: NavItem\[\]/);
assert.match(nav, /path: '\/workspace\/home'/);
assert.match(nav, /path: '\/workspace\/customers'/);
assert.match(nav, /path: '\/workspace\/sales'/);
assert.match(nav, /path: '\/workspace\/commerce'/);
assert.match(nav, /path: '\/workspace\/finance'/);
assert.match(nav, /path: '\/workspace\/work'/);
assert.match(nav, /path: '\/workspace\/reports'/);
assert.match(nav, /path: '\/workspace\/organization'/);
assert.match(read('src/components/ModuleLandingWorkspace.tsx'), /canAccess\(item\.perm\)/, 'landing tiles must be RBAC-filtered');
assert.match(drawer, /item\.children/);
assert.match(sidebar, /item\.children/);
assert.doesNotMatch(line, /glow\(/, 'line charts should avoid decorative glow');
assert.match(line, /var\(--color-chart-grid\)/);
assert.match(bar, /var\(--color-chart-grid\)/);
