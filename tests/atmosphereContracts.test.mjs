import fs from 'node:fs';
import assert from 'node:assert/strict';
const component = fs.readFileSync('src/components/AtmosphereLayer.tsx','utf8');
const css = fs.readFileSync('src/index.css','utf8');
const version = fs.readFileSync('src/lib/version.ts','utf8');
const pkg = JSON.parse(fs.readFileSync('package.json','utf8'));
const metadata = JSON.parse(fs.readFileSync('metadata.json','utf8'));
assert.match(component,/se-sky-moon/,'moon atmospheric layer exists');
assert.match(component,/se-sky-cloud-1/,'cloud drift layers exist');
assert.match(css,/@keyframes se-cloud-drift/,'legacy cloud animation definition remains available but is not rendered');
assert.match(css,/se-atmosphere-root .*display: none !important/,'decorative atmosphere is disabled for the minimalist workspace');
assert.match(css,/prefers-reduced-motion:\s*reduce/,'system reduced-motion preference is respected');
assert.match(css,/data-performance-mode="low"[\s\S]*?se-sky-clouds/,'low-performance mode reduces cloud layer');
assert.match(css,/96s ease-in-out/,'cloud motion is slow and non-distracting');
assert.match(pkg.version,/^\d+\.\d+\.\d+$/,'package version is semver');
assert.ok(version.includes(`APP_VERSION = '${pkg.version}'`),'app version synchronized');
assert.match(version,/r14-cp28-reportsworkspace-any-reduction/,'app release label synchronized');
assert.equal(metadata.version,pkg.version,'metadata version synchronized');
assert.equal(metadata.release,'r14-cp28-reportsworkspace-any-reduction','metadata release synchronized');
console.log('PASS: 11 assertions (iOS-style atmosphere, reduced motion, low graphics and release metadata)');
