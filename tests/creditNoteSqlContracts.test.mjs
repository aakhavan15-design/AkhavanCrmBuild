import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { creditNoteEvidenceSql, projectCreditNoteEvidence, CREDIT_NOTE_EVIDENCE_LIMIT } from '../server/creditNoteEvidence.mjs';
const root=path.resolve(new URL('..',import.meta.url).pathname);
const mirror=fs.readFileSync(path.join(root,'database/sqlserver/v1/003_external_mirror_and_finance.sql'),'utf8');
const rls=fs.readFileSync(path.join(root,'database/sqlserver/v1/006_row_level_security.sql'),'utf8');
assert.ok(mirror.includes('CREATE TABLE crm.CreditNoteMirror'),'ERP credit notes are modeled as a mirror, not a CRM-originated ledger');
assert.ok(mirror.includes('ExternalCreditNoteId')&&mirror.includes('SourceSystemCode'),'credit mirror has stable external identity and source-system identity');
assert.ok(mirror.includes('InvoiceMirrorId')&&mirror.includes('AccountId')&&mirror.includes('Amount'),'credit mirror can link to invoice/account and amount');
assert.ok(mirror.includes("cn.StatusCode IN ('POSTED','APPROVED')")&&mirror.includes('cn.IsVoided=0'),'canonical balance view subtracts only non-void approved/posted credits');
assert.ok(mirror.includes('CREATE OR ALTER VIEW analytics.vw_InvoiceBalance'),'single SQL balance view is the canonical balance contract');
assert.ok(rls.includes('ON crm.CreditNoteMirror'),'credit mirror is included in tenant row-level security policy');
assert.match(creditNoteEvidenceSql, /invoice.TenantId=credit.TenantId AND invoice.InvoiceMirrorId=credit.InvoiceMirrorId/);
assert.match(creditNoteEvidenceSql, /account.TenantId=credit.TenantId AND account.AccountId=credit.AccountId/);
assert.match(creditNoteEvidenceSql, /WHERE credit.TenantId=@tenantId AND credit.IsVoided=0 AND credit.StatusCode IN \('POSTED','APPROVED'\)/);
assert.match(creditNoteEvidenceSql, /security.fn_RecordReadScope\(\s*credit.TenantId,N'finance.view',account.OwnerUserId,account.BranchId,account.TerritoryId,account.TeamId/);
assert.match(creditNoteEvidenceSql, /CASE WHEN link.EvidenceCode='LINKED' THEN invoice.InvoiceNumber END/);
assert.match(creditNoteEvidenceSql, /credit.AccountId<>invoice.AccountId THEN 'ACCOUNT_MISMATCH'/);
assert.doesNotMatch(creditNoteEvidenceSql, /credit.Amount/);
assert.deepEqual(projectCreditNoteEvidence([]), { status: 'EMPTY', items: [], hasMore: false });
const more = projectCreditNoteEvidence(Array.from({ length: CREDIT_NOTE_EVIDENCE_LIMIT + 1 }, (_, id) => ({ id })));
assert.equal(more.items.length, CREDIT_NOTE_EVIDENCE_LIMIT);
assert.equal(more.status, 'AVAILABLE');
assert.equal(more.hasMore, true);
const server = fs.readFileSync(path.join(root,'server/index.mjs'),'utf8');
assert.match(server, /app.get\('\/api\/v1\/ledger\/credit-notes', authenticate, requirePermission\('finance.view'\)/);
const reports = fs.readFileSync(path.join(root,'src/components/ReportsHub.tsx'),'utf8');
assert.match(reports, /provider.getCreditNoteEvidence\(\)/);
assert.match(reports, /ledgerBalances=\{result\}/);
assert.match(reports, /creditNotes.data.status === 'RESTRICTED'/);
console.log('PASS: ERP credit-note mirror, evidence projection, canonical balance view and scoped report');
