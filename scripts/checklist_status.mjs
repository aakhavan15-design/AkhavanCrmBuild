#!/usr/bin/env node
/**
 * Deterministic and auditable status summary for docs/CHECKLIST_FA.md.
 * No count is accepted from a prose claim, historical snapshot or regex-only
 * "VERIFIED" mention. One checklist marker = one counted row.
 *
 * Usage:
 *   node scripts/checklist_status.mjs --check
 *   node scripts/checklist_status.mjs --write
 */
import { readFileSync, writeFileSync } from 'node:fs';
const filename = 'docs/CHECKLIST_FA.md';
const original = readFileSync(filename,'utf8');
const rows = original.split(/\r?\n/).filter(line => /^\s*-\s+\[[x~BF ]\]\s/.test(line));
const statuses = { x:0, '~':0, B:0, F:0, ' ':0 };
const withF = [];
const ids = [];
for (const row of rows) {
  const marker = row.match(/^\s*-\s+\[([x~BF ])\]\s/)[1];
  statuses[marker]++;
  const found = [...row.matchAll(/\bF\d+-\d+\b/g)].map(m=>m[0]);
  if (found.length) { withF.push(row); ids.push(...found); }
}
const unique = new Set(ids);
const collisions = ids.length - unique.size;
const report = [
  '<!-- CHECKLIST_STATUS:BEGIN generated by scripts/checklist_status.mjs -->',
  '## وضعیت قابل شمارش چک‌لیست — خروجی خودکار',
  '',
  '| وضعیت نشانه | تعداد |',
  '|---|---:|',
  `| انجام‌شده با شاهد محدوده‌ای \`[x]\` | ${statuses.x} |`,
  `| ناقص یا آزمون‌نشده \`[~]\` | ${statuses['~']} |`,
  `| وابسته به محیط خارجی \`[B]\` | ${statuses.B} |`,
  `| تعریف‌نشده \`[ ]\` | ${statuses[' ']} |`,
  `| فریز مصوب \`[F]\` | ${statuses.F} |`,
  `| **کل ردیف‌های علامت‌دار** | **${rows.length}** |`,
  '',
  `ردیف‌های دارای شناسه F: **${withF.length}**؛ تعداد شناسه F یکتا: **${unique.size}**؛ تکرار شناسه در متن: **${collisions}**. شناسه تکراری لزوماً آیتم تکراری نیست؛ فقط علامت هشدار ممیزی است.`,
  '',
  '> این‌ها وضعیت مستندات هستند، نه شمار قابلیت‌های تأییدشده عملیاتی. DONE فقط با هفت دروازهٔ پذیرش و شواهد رفتاری ثبت می‌شود؛ BLOCKED خارجی نباید پیشرفت مستقل را متوقف کند.',
  '<!-- CHECKLIST_STATUS:END -->',
].join('\n');
const begin = '<!-- CHECKLIST_STATUS:BEGIN generated by scripts/checklist_status.mjs -->';
const end = '<!-- CHECKLIST_STATUS:END -->';
const start = original.indexOf(begin);
const finish = original.indexOf(end);
if(start<0 || finish<start) throw new Error('Checklist summary markers not found; run migration once before checking.');
const revised = original.slice(0,start) + report + original.slice(finish+end.length);
if(process.argv.includes('--write')) {
  if (revised!==original)writeFileSync(filename,revised);
  console.log(JSON.stringify({total:rows.length,byMarker:statuses,uniqueF:unique.size,modified:revised!==original}));
} else if(revised!==original) {
  console.error('Checklist summary is stale. Run node scripts/checklist_status.mjs --write');
  process.exitCode=1;
} else console.log(JSON.stringify({status:'PASS',total:rows.length,byMarker:statuses,uniqueF:unique.size}));
